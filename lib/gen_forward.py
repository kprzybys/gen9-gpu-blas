"""Generates gen9blas_blas_forward.c: jumps to the CPU BLAS (OpenBLAS) for the BLAS symbols that gen9blas_blas.c does not implement.

Run: python3 gen_forward.py blas_symbols.txt gen9blas_blas.c [gen9blas_blas_d.inc ...] > gen9blas_blas_forward.c   (the Makefile does this)
blas_symbols.txt: exports of the system libblas.so.3 (nm -D --defined-only, OpenBLAS 0.3, 393 symbols: CBLAS
and Fortran names). Functions implemented in gen9blas_blas.c are marked with the BLAS_API macro. Every other symbol is
`jmp *gen9blas_fwd_target[i](%rip)` -- arguments and result pass through unchanged, so signatures are not needed. The
gen9blas_fwd_target addresses are filled in by gen9blas_blas.c (constructor) through dlsym from the CPU library.
"""
import re
import sys

symbols = [l.strip() for l in open(sys.argv[1]) if l.strip()]
own = set()
for path in sys.argv[2:]:
    own |= set(re.findall(r"^BLAS_API\b[^(]*?\b(\w+)\s*\(", open(path).read(), re.M))
missing = own - set(symbols)
if missing:
    sys.exit(f"gen_forward: functions not in the BLAS list: {sorted(missing)}")
forwarded = [s for s in symbols if s not in own]
print("// Generated by gen_forward.py -- do not edit. Jumps to the CPU BLAS for functions outside gen9blas_blas.c.")
print(f"// Own: {len(own)}, forwarded: {len(forwarded)}.")
print(f"#define GEN9BLAS_NFWD {len(forwarded)}")
print("__attribute__((visibility(\"hidden\"))) void *gen9blas_fwd_target[GEN9BLAS_NFWD];")
print("__attribute__((visibility(\"hidden\"))) const int gen9blas_nfwd = GEN9BLAS_NFWD;")
print("__attribute__((visibility(\"hidden\"))) const char *const gen9blas_fwd_names[GEN9BLAS_NFWD] = {")
for s in forwarded:
    print(f'    "{s}",')
print("};")
print("__asm__(\".text\\n\"")
for i, s in enumerate(forwarded):
    print(f'        ".globl {s}\\n.type {s},@function\\n{s}: jmp *gen9blas_fwd_target+{8 * i}(%rip)\\n"')
print(");")
