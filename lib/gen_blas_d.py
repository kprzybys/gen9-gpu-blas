"""Generates gen9blas_blas_d.inc: the D (FP64) functions of the BLAS layer from the S function code in gen9blas_blas.c.

Run: python3 gen_blas_d.py gen9blas_blas.c > gen9blas_blas_d.inc   (the Makefile does this)
The fragment from "BEGIN TYPE" to "END TYPE" (without the "S only" blocks): static functions and typedefs get a _d suffix
(same source file -- no collisions), float -> double, GEN9BLAS_S -> GEN9BLAS_D, exported names and strings s -> d
(cblas_sgemm -> cblas_dgemm, sgemm_ -> dgemm_, isamax -> idamax).
"""
import re
import sys

s = open(sys.argv[1]).read()
t = s[s.index("// ==== BEGIN TYPE"):s.index("// ==== END TYPE")]
t = re.sub(r"// ---- S only: begin.*?// ---- S only: end\n", "", t, flags=re.S)
statics = set(re.findall(r"^static\b[^(=;]*?\b(\w+)\s*\(", t, re.M)) | set(re.findall(r"^typedef\b.*?\b(\w+);", t, re.M)) \
    | set(re.findall(r"^typedef\b[^;]*?\(\*(\w+)\)", t, re.M))
for n in sorted(statics, key=len, reverse=True):
    t = re.sub(r"\b" + n + r"\b", n + "_d", t)
t = re.sub(r"\bfloat\b", "double", t)
t = t.replace("GEN9BLAS_S", "GEN9BLAS_D")
t = re.sub(r"\bcblas_s(\w+)", r"cblas_d\1", t)
t = re.sub(r"\bcblas_isamax\b", "cblas_idamax", t)
t = re.sub(r"\bs(gemm|symm|syrk|syr2k|trmm|trsm|gemv|ger|symv|trmv|trsv|syr|syr2|gbmv|sbmv|tbmv|tbsv|spmv|tpmv|tpsv|spr|spr2)_\b", r"d\1_", t)
t = re.sub(r'"s([a-z0-9]+_?)"', r'"d\1"', t)
t = t.replace('"isamax"', '"idamax"')
t = t.replace("// ==== BEGIN TYPE", "// ==== BEGIN TYPE (D version)")
print("// Generated by gen_blas_d.py from gen9blas_blas.c -- do not edit.")
print(t)
