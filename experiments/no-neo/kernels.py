"""Turns a zebin binary (from ocloc) into a C header: kernel ISA code and a description of its data (argument offsets from .ze_info).

Run: python3 kernels.py <file.bin> <ze_info> > kernels.h   (ze_info: from `ocloc disasm -dump <dir>`)
Supported: global pointers, stateless (64-bit address) and stateful (binding table + buffer_address/buffer_offset),
by-value arguments, local_size, enqueued_local_size, global_id_offset, private_base_stateless (zero), local IDs.
Anything else (scratch, SLM, images, sampler) -> error, so that a kernel is never launched with incomplete state.
"""
import struct
import sys

import yaml

zebin, zeinfo = sys.argv[1], sys.argv[2]
only = set(sys.argv[3].split(",")) if len(sys.argv) > 3 else None   # optional: list of kernels
d = open(zebin, "rb").read()
shoff, = struct.unpack_from("<Q", d, 0x28)
shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x3A)
sections = [struct.unpack_from("<IIQQQQIIQQ", d, shoff + i * shentsize) for i in range(shnum)]
stroff = sections[shstrndx][4]
texts = {}
for s in sections:
    name = d[stroff + s[0]:d.index(b"\0", stroff + s[0])].decode()
    if name.startswith(".text."):
        texts[name[6:]] = d[s[4]:s[4] + s[5]]

info = yaml.safe_load(open(zeinfo))
print("// Generated by experiments/no-neo/kernels.py -- do not edit.")
print("#pragma once\n#include <stdint.h>\n#include \"gen9i.h\"\n")
for k in info["kernels"]:
    n, env = k["name"], k["execution_env"]
    if n not in texts or (only and n not in only):
        continue
    for key in ("per_thread_scratch_size", "slm_size", "barrier_count"):
        if env.get(key):
            sys.exit(f"kernels.py: {n}: {key} = {env[key]} -- not supported yet")
    bti = {b["arg_index"]: b["bti_value"] for b in k.get("binding_table_indices", [])}
    arg = {}          # index -> [offset, size, bti, buffer_address offset, buffer_offset offset]
    spec = {"local_size": [], "enqueued_local_size": [], "global_id_offset": [], "private_base_stateless": []}
    end = 0
    for a in k.get("payload_arguments", []):
        t = a["arg_type"]
        if t in ("arg_bypointer", "arg_byvalue"):
            i = a["arg_index"]
            e = arg.setdefault(i, [-1, 0, -1, -1, -1])
            if t == "arg_bypointer" and a.get("addrmode") == "stateful":
                if a.get("addrspace") != "global":
                    sys.exit(f"kernels.py: {n}: argument {i}: {a.get('addrspace')} -- not supported yet")
                e[2] = bti[i]
            elif t == "arg_bypointer" and a.get("addrmode") != "stateless":
                sys.exit(f"kernels.py: {n}: argument {i}: mode {a.get('addrmode')}")
            else:
                e[0], e[1] = a["offset"], a["size"]
        elif t == "buffer_address":
            arg.setdefault(a["arg_index"], [-1, 0, -1, -1, -1])[3] = a["offset"]
        elif t == "buffer_offset":
            arg.setdefault(a["arg_index"], [-1, 0, -1, -1, -1])[4] = a["offset"]
        elif t in spec:
            spec[t].append(a["offset"])
        else:
            sys.exit(f"kernels.py: {n}: unsupported argument {t}")
        end = max(end, a["offset"] + a["size"])
    pt = sum(a["size"] for a in k.get("per_thread_payload_arguments", []))
    isa = texts[n]
    print(f"static const uint8_t {n}_isa[{len(isa)}] = {{")
    for i in range(0, len(isa), 24):
        print("    " + ", ".join(f"0x{b:02x}" for b in isa[i:i + 24]) + ",")
    print("};")
    if sorted(arg) != list(range(len(arg))):
        sys.exit(f"kernels.py: {n}: arguments not consecutive: {sorted(arg)}")
    offs = ", ".join("{" + ", ".join(str(x) for x in arg[i]) + "}" for i in sorted(arg))
    def as_list(xs):
        return "{" + ", ".join(str(x) for x in (xs + [-1, -1, -1])[:3]) + "}"
    print(f"static const struct g9i_kernel {n}_kernel = {{ \"{n}\", {n}_isa, sizeof {n}_isa, {env['simd_size']}, "
          f"{env.get('grf_count', 128)}, {(end + 31) // 32 * 32}, {pt}, {len(arg)}, {{ {offs} }}, "
          f"{as_list(spec['local_size'])}, {as_list(spec['enqueued_local_size'])}, {as_list(spec['global_id_offset'])}, "
          f"{max(bti.values()) + 1 if bti else 0} }};\n")
